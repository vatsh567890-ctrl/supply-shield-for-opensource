"""Generate docs/status.md tracking module completeness and NotImplementedError occurrences."""

import os
from pathlib import Path


def generate_status_report() -> tuple[str, int, int, int]:
    root_dir = Path(__file__).resolve().parent.parent
    app_dir = root_dir / "backend" / "app"

    modules: list[dict[str, str | int | bool]] = []
    total_nie_count = 0

    for current_root, _, files in os.walk(app_dir):
        for f in sorted(files):
            if f.endswith(".py"):
                file_path = Path(current_root) / f
                rel_path = file_path.relative_to(root_dir).as_posix()
                content = file_path.read_text(encoding="utf-8")

                has_nie = "NotImplementedError" in content
                count = content.count("NotImplementedError")
                total_nie_count += count

                status = "Stub (In Progress)" if has_nie else "Complete"
                modules.append({
                    "path": rel_path,
                    "has_nie": has_nie,
                    "count": count,
                    "status": status,
                })

    total_modules = len(modules)
    stub_modules = sum(1 for m in modules if m["has_nie"])
    complete_modules = total_modules - stub_modules

    # Build Markdown document
    lines = [
        "# SupplyShield Backend Module Status",
        "",
        "> **Generated Report**: Tracks implementation completeness across all `backend/app/` modules.",
        "> Generated by command: `python scripts/generate_status.py`",
        "",
        "## Summary Metrics",
        "",
        f"- **Total Modules Scanned**: {total_modules}",
        f"- **Complete Modules**: {complete_modules}",
        f"- **Stub / In Progress Modules**: {stub_modules}",
        f"- **Total `NotImplementedError` Occurrences**: {total_nie_count}",
        "",
        "## Verification Rule",
        "",
        "Modules marked **Complete** must strictly contain zero `NotImplementedError` occurrences.",
        "CI verifies this via `python scripts/check_module_status.py`.",
        "",
        "## Module Inventory",
        "",
        "| Module Path | Status | `NotImplementedError` Count |",
        "| :--- | :--- | :--- |",
    ]

    for m in sorted(modules, key=lambda x: str(x["path"])):
        count_str = str(m["count"]) if m["count"] > 0 else "0"
        status_str = f"**{m['status']}**" if m["status"] == "Complete" else str(m["status"])
        lines.append(f"| `{m['path']}` | {status_str} | {count_str} |")

    lines.append("")
    report_text = "\n".join(lines)
    return report_text, total_modules, complete_modules, stub_modules


if __name__ == "__main__":
    report, total, complete, stubs = generate_status_report()
    out_path = Path(__file__).resolve().parent.parent / "docs" / "status.md"
    out_path.write_text(report, encoding="utf-8")
    print(f"Generated docs/status.md: {total} modules ({complete} complete, {stubs} stubs).")

